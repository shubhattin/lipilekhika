function get_list(specific_text: string, custom_normal_keys: string | string[]) {
  const keys = typeof custom_normal_keys === 'string' ? [custom_normal_keys] : custom_normal_keys;
  return keys.map((custom_normal_key) => ({
    type: 'custom_script_char' as const,
    custom_normal_key,
    specific_text
  }));
}

