//! Generates the transliteration test data of the standard romanization schemes with
//! [`vidyut-lipi`](https://github.com/ambuda-org/vidyut) (MIT) as the reference.
//!
//! Run by hand from this directory, the output is committed (it is not regenerated in CI):
//!
//! ```sh
//! cargo run --release                  # all the schemes
//! cargo run --release -- SLP1 ITRANS   # only some of them
//! ```
//!
//! For each scheme it writes `test_data/transliteration/std-<scheme>/std-<scheme>[-N].yaml`
//! (replacing what was there) with the Devanagari inputs of `scripts/sanskrit-inputs.txt` and
//! `scripts/vedic-inputs.txt` and their vidyut output. An input is left out when vidyut leaves
//! a Devanagari character in its output (a character it has no form for in that scheme, like
//! the Vedic accents in Harvard-Kyoto). A case is `reversible` when vidyut reads its output
//! back to the input.

use std::fs;
use std::path::{Path, PathBuf};

use vidyut_lipi::{Lipika, Scheme};

/// lipilekhika script name and the vidyut scheme
const SCHEMES: &[(&str, Scheme)] = &[
    ("SLP1", Scheme::Slp1),
    ("Harvard-Kyoto", Scheme::HarvardKyoto),
];

/// Cases in a file, like the `auto-*` test data
const CHUNK_SIZE: usize = 41;

/// Where lipilekhika intentionally writes differently from vidyut, the vidyut output is changed
/// to the lipilekhika form.
fn normalize_output(script: &str, output: &str) -> String {
    match script {
        // ळ्ह is written as its letters (`Lh`), lipilekhika has no single form for a conjunct
        "SLP1" => move_accents_after(&output.replace('|', "Lh"), &["\\", "^"], &["M", "H", "~"]),
        _ => output.to_string(),
    }
}

/// vidyut writes a Vedic accent before the anusvAra / visarga / candrabindu that comes before it
/// in the Devanagari (मीं॒ -> `mI\M`), lipilekhika keeps the order of the Devanagari (`mIM\`).
/// The inputs always have the accent after them (checked in `main`), so every such pair is
/// swapped back.
fn move_accents_after(output: &str, accents: &[&str], marks: &[&str]) -> String {
    let mut res = output.to_string();
    for accent in accents {
        for mark in marks {
            res = res.replace(&format!("{accent}{mark}"), &format!("{mark}{accent}"));
        }
    }
    res
}

/// A Vedic accent written before an anusvAra / visarga / candrabindu, see `move_accents_after`
fn has_accent_before_mark(input: &str) -> bool {
    let chars: Vec<char> = input.chars().collect();
    chars.windows(2).any(|w| {
        matches!(w[0], '\u{0951}' | '\u{0952}' | '\u{1CDA}' | '\u{1CDB}')
            && matches!(w[1], '\u{0901}' | '\u{0902}' | '\u{0903}')
    })
}

/// A Devanagari or Vedic Extensions character left in the output by vidyut
fn has_unmapped_char(output: &str) -> bool {
    output
        .chars()
        .any(|c| ('\u{0900}'..='\u{097F}').contains(&c) || ('\u{1CD0}'..='\u{1CFF}').contains(&c))
}

fn read_inputs(path: &Path) -> Vec<String> {
    fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("could not read {}: {e}", path.display()))
        .split("\n\n")
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
        .collect()
}

fn yaml_string(s: &str) -> String {
    // a JSON string is a valid YAML double quoted scalar
    serde_json::to_string(s).expect("string serializes")
}

struct Case {
    input: String,
    output: String,
    reversible: bool,
}

fn write_cases(out_dir: &Path, base_name: &str, script: &str, cases: &[Case]) {
    if out_dir.exists() {
        fs::remove_dir_all(out_dir).expect("remove the old test data");
    }
    fs::create_dir_all(out_dir).expect("create the test data folder");
    let chunks: Vec<&[Case]> = cases.chunks(CHUNK_SIZE).collect();
    for (chunk_index, chunk) in chunks.iter().enumerate() {
        let suffix = if chunks.len() > 1 {
            format!("-{}", chunk_index + 1)
        } else {
            String::new()
        };
        let mut yaml = String::from(
            "# Generated by scripts/tools/vidyut-test-data from the vidyut-lipi output (MIT).\n\
             # Do not edit by hand, rerun the generator instead.\n",
        );
        for (index, case) in chunk.iter().enumerate() {
            yaml.push_str(&format!(
                "- index: {index}\n  from: Devanagari\n  to: {script}\n  input: {}\n  output: {}\n  reversible: {}\n",
                yaml_string(&case.input),
                yaml_string(&case.output),
                case.reversible
            ));
        }
        fs::write(out_dir.join(format!("{base_name}{suffix}.yaml")), yaml)
            .expect("write the test data");
    }
}

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../..");
    let mut inputs = read_inputs(&root.join("scripts/sanskrit-inputs.txt"));
    inputs.extend(read_inputs(&root.join("scripts/vedic-inputs.txt")));

    let selected: Vec<String> = std::env::args().skip(1).collect();
    for name in &selected {
        assert!(
            SCHEMES.iter().any(|(s, _)| s == name),
            "unknown scheme {name}, expected one of {:?}",
            SCHEMES.iter().map(|(s, _)| *s).collect::<Vec<_>>()
        );
    }

    let mut lipika = Lipika::new();
    for &(script, scheme) in SCHEMES {
        if !selected.is_empty() && !selected.iter().any(|s| s == script) {
            continue;
        }
        let mut cases = Vec::new();
        let mut skipped = 0;
        for input in &inputs {
            assert!(
                !has_accent_before_mark(input),
                "an accent before an anusvAra / visarga, `move_accents_after` would reorder it: {input}"
            );
            let output = lipika.transliterate(input, Scheme::Devanagari, scheme);
            if has_unmapped_char(&output) {
                skipped += 1;
                continue;
            }
            let reversible = lipika.transliterate(&output, scheme, Scheme::Devanagari) == *input;
            cases.push(Case {
                input: input.clone(),
                output: normalize_output(script, &output),
                reversible,
            });
        }
        let base_name = format!("std-{}", script.to_lowercase());
        write_cases(
            &root.join("test_data/transliteration").join(&base_name),
            &base_name,
            script,
            &cases,
        );
        println!(
            "{script}: {} cases ({} reversible), {skipped} inputs left out",
            cases.len(),
            cases.iter().filter(|c| c.reversible).count()
        );
    }
}
